// Pins the poses the pre-P3 performance layer (167ece9) settles to, so the
// profile engine can prove Hiyori's original tones did not move.
//
//   node scripts/avatar-performance-snapshot.mjs [module] [output]
//
// module defaults to src/avatar-performance.ts and output to
// src/avatar-performance.snapshot.json; SNAPSHOT_SOURCE labels the module in
// the output. It was run once, against a copy of 167ece9's
// src/avatar-performance.ts (and shared/performance-cues.mjs beside it);
// src/avatar-performance-profile.test.mjs replays the same grid through the
// new engine and compares.
import { EventEmitter } from 'node:events'
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

export const SNAPSHOT_GRID = Object.freeze({
  tones: ['neutral', 'happy', 'soft', 'curious', 'surprised', 'sad', 'pout', 'shy', 'bright', 'invented'],
  activities: ['idle', 'attentive', 'thinking', 'speaking'],
  // setMouth arguments; silent never calls it.
  mouths: { silent: null, audio: [0.55, 0.21], aligned: [0.55, -0.27, 0.6], browser: [null, 0] },
  smiles: [0, 0.5, 1],
  brows: [-1, 0, 0.3, 0.667, 1],
  pitches: [-30, 0, 17],
})
// The old faces eased exponentially and only reach 0.9999999999999996
// after this many 50 ms frames.
export const SNAPSHOT_FRAMES = 400
export const SNAPSHOT_FRAME_MS = 50

export function* snapshotCases() {
  const { tones, activities, mouths, smiles, brows, pitches } = SNAPSHOT_GRID
  for (const tone of tones) for (const activity of activities) for (const mouth of Object.keys(mouths))
    for (const smile of smiles) for (const brow of brows) for (const pitch of pitches)
      yield { tone, activity, mouth, smile, brow, pitch }
}

// The motion baseline Cubism restores before every beforeModelUpdate: an
// Idle-like open mouth and model-default form, plus the case's smile, brow
// and pitch. Like the unit-test fixture, the core does not clamp.
export function snapshotBaseline({ smile, brow, pitch }) {
  return {
    ParamMouthOpenY: 1,
    ParamMouthForm: -1,
    ParamCheek: smile,
    ParamEyeLSmile: smile,
    ParamEyeRSmile: smile,
    ParamBrowLForm: brow,
    ParamBrowRForm: brow,
    ParamAngleY: pitch,
  }
}

export function settlePose(attach, testCase, options = {}) {
  let time = 0
  const values = new Map()
  const model = new EventEmitter()
  model.coreModel = {
    getParameterValueById: id => values.get(id) ?? 0,
    setParameterValueById: (id, value, weight = 1) => values.set(id, (values.get(id) ?? 0) * (1 - weight) + value * weight),
    addParameterValueById: (id, value) => values.set(id, (values.get(id) ?? 0) + value),
  }
  const actor = attach(model, { ...options, now: () => time })
  actor.setActivity(testCase.activity)
  actor.setDelivery(testCase.tone)
  const mouth = SNAPSHOT_GRID.mouths[testCase.mouth]
  if (mouth) actor.setMouth(...mouth)
  const baseline = Object.entries(snapshotBaseline(testCase))
  for (let index = 0; index < SNAPSHOT_FRAMES; index++) {
    time += SNAPSHOT_FRAME_MS
    values.clear()
    for (const [id, value] of baseline) values.set(id, value)
    model.emit('beforeModelUpdate')
  }
  actor.destroy()
  return Object.fromEntries(values)
}

// 15 significant digits keep the file small and lose at most ~1e-14 on
// values within ±30, far inside the 1e-12 the tests allow.
const round = value => Number(value.toPrecision(15))

export function buildSnapshot(attach, source) {
  const poses = []
  const keys = new Set()
  for (const testCase of snapshotCases()) {
    const pose = settlePose(attach, testCase)
    for (const key of Object.keys(pose)) keys.add(key)
    poses.push(pose)
  }
  const order = [...keys].sort()
  // Identical rows are stored once; cases index them in snapshotCases() order.
  const rows = []
  const rowIndex = new Map()
  const cases = poses.map(pose => {
    const row = order.map(key => key in pose ? round(pose[key]) : null)
    const text = JSON.stringify(row)
    if (!rowIndex.has(text)) {
      rowIndex.set(text, rows.length)
      rows.push(row)
    }
    return rowIndex.get(text)
  })
  return {
    _notes: [
      'Generated by scripts/avatar-performance-snapshot.mjs. Do not edit.',
      'Each case of snapshotCases() settles for frames × frameMs on the baseline of snapshotBaseline(); cases[i] indexes rows, whose values follow keys (null: never written).',
    ],
    source,
    frames: SNAPSHOT_FRAMES,
    frameMs: SNAPSHOT_FRAME_MS,
    grid: SNAPSHOT_GRID,
    keys: order,
    rows,
    cases,
  }
}

// One row per line and 72 case indices per line, so a regenerated file diffs readably.
export function formatSnapshot(snapshot) {
  const lines = []
  for (const [key, value] of Object.entries(snapshot)) {
    if (key === 'rows')
      lines.push(`  "rows": [\n${value.map(row => `    ${JSON.stringify(row)}`).join(',\n')}\n  ]`)
    else if (key === 'cases') {
      const chunks = []
      for (let start = 0; start < value.length; start += 72) chunks.push(`    ${value.slice(start, start + 72).join(',')}`)
      lines.push(`  "cases": [\n${chunks.join(',\n')}\n  ]`)
    }
    else lines.push(`  ${JSON.stringify(key)}: ${JSON.stringify(value)}`)
  }
  return `{\n${lines.join(',\n')}\n}\n`
}

// Expands a stored snapshot back into one pose object per case.
export function snapshotPoses(snapshot) {
  return snapshot.cases.map(index => {
    const pose = {}
    snapshot.rows[index].forEach((value, column) => {
      if (value !== null) pose[snapshot.keys[column]] = value
    })
    return pose
  })
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const modulePath = process.argv[2] ? resolve(process.argv[2]) : new URL('../src/avatar-performance.ts', import.meta.url)
  const output = process.argv[3] ? resolve(process.argv[3]) : new URL('../src/avatar-performance.snapshot.json', import.meta.url)
  const moduleUrl = modulePath instanceof URL ? modulePath : pathToFileURL(modulePath)
  const { attachAvatarPerformance } = await import(moduleUrl.href)
  const snapshot = buildSnapshot(attachAvatarPerformance, process.env.SNAPSHOT_SOURCE ?? 'src/avatar-performance.ts')
  writeFileSync(output, formatSnapshot(snapshot))
  console.log(`${snapshot.cases.length} cases, ${snapshot.rows.length} distinct poses, ${snapshot.keys.length} keys -> ${output instanceof URL ? output.pathname : output}`)
}
